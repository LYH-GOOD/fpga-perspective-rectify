//=============================================================================
// div_seq.v
//   顺序除法器（radix-2 恢复余数法）—— 替代行为级 '/' 的"保底"实现
//
//---------------------------------------------------------------------------
//   为什么必须换掉行为级 '/'
//---------------------------------------------------------------------------
//   Verilog 的 '/' 会被综合成一个【全组合】的除法阵列：几千个 LUT、
//   关键路径几百 ns，100 MHz 下必然时序不收敛。仿真没问题，上板一定失败。
//
//   本模块用"一拍一位"的顺序算法，资源小、时序好，代价是慢：
//       一次除法 = WA + 1 拍
//
//---------------------------------------------------------------------------
//   「保底」的定性 —— 2026-09-27 更新：它已经是提速后的正式实现
//---------------------------------------------------------------------------
//   蓝图原方案是【倒数查表 + 牛顿迭代】（A5 结论）。**该路线已放弃**：
//   实测两条路收益相当（并行 ~4.5× vs 倒数 ~5×），但倒数+牛顿是近似算法，
//   要维持"与逐位模型逐字节一致"必须补精确校正，风险高一个数量级。
//   实际走的是【在 coord_gen 里放 8 路并行 div_seq】（本模块一字不改算法）：
//      每像素 60 拍 → 12 拍，且与串行版【逐字节一致】（实测 diff 全空）。
//
//   ⚠️ 但"本模块算法不变"**不等于**"接口时序可以随便变"：
//      并行化后上游的操作数总线每几拍就换，本模块内部任何"顺手用一下当拍输入"
//      的写法都会算错。所以启动时把 a / b / 商的符号全部锁存（见下面 q_neg_r /
//      b_lat），迭代过程中只认寄存器 —— 本模块必须是 (启动时的 a, 启动时的 b)
//      的【纯函数】。这一条踩过两次（符号、除数各一次），有专门的回归用例
//      （div_seq_tb 的 [5] 组"运行中更换操作数总线"）。
//
//---------------------------------------------------------------------------
//   算法（无符号部分）
//---------------------------------------------------------------------------
//       rem = 0
//       重复 WA 次：
//          rem = (rem << 1) | a 的最高位      ← 逐位从被除数拉进来
//          if (rem >= b) { rem -= b; 商该位 = 1 } else 商该位 = 0
//
//   有符号处理：对 |a|、|b| 做无符号除法，商的符号 = a符号 ^ b符号，
//   语义是【向零截断】—— 与原行为级 '/' 一致（不是向下取整）。
//
//   除数为 0：输出 0 并置 div_zero，不产生不定态。
//=============================================================================
`timescale 1ns / 1ps

module div_seq #(
    parameter integer WA = 48,      // 被除数位宽（有符号）
    parameter integer WB = 32,      // 除数位宽（有符号）
    parameter integer WQ = 48       // 商位宽（有符号，须 >= WA）
)(
    input  wire                 clk,
    input  wire                 rst_n,       // 同步低电平复位

    input  wire                 start,       // 1 拍脉冲；start 时采样 a / b
    input  wire signed [WA-1:0] a,
    input  wire signed [WB-1:0] b,

    output reg  signed [WQ-1:0] q,
    output reg                  done,        // 1 拍脉冲，比 start 晚 WA+1 拍
    output reg                  div_zero     // 除数为 0（与 done 同拍）
);

    localparam integer ITER = WA;

    //------------------------------------------------------------------------
    // 符号处理：取绝对值做无符号除法，再补符号
    //------------------------------------------------------------------------
    wire               a_neg = a[WA-1];
    wire               b_neg = b[WB-1];
    wire [WA-1:0]      a_abs = a_neg ? (~a + 1'b1) : a;
    wire [WB-1:0]      b_abs = b_neg ? (~b + 1'b1) : b;
    wire               q_neg = a_neg ^ b_neg;
    wire               b_zero = (b == {WB{1'b0}});

    //   ⚠️⚠️ 除数必须【在启动那一拍锁存】再进迭代 —— 同一类坑的第二处
    //      （2026-09-27，N 路并行后才暴露，比符号那处更隐蔽）：
    //      b_ext = {1'b0, b_abs} 是【组合】的，而它被用在【每一次迭代】的比较里。
    //      上游一旦在 49 拍内换了操作数总线，除数就在算法【运行中】被改掉 ——
    //      rem/trial 的比较基准变了，商自然偏一点。
    //      现象：同样的 (a,b)，N=1 与 N=8 的结果差几十 LSB（0.001 px 量级），
    //            N=1 时上游会等 done 才换操作数，所以侥幸完全正确。
    //      ⇒ div_seq 必须是 (启动时的 a, 启动时的 b) 的【纯函数】。
    reg  [WB:0]        b_lat;       // 锁存的除数（多 1 位，与 trial 同宽）

    //------------------------------------------------------------------------
    // 迭代寄存器
    //------------------------------------------------------------------------
    reg [WA-1:0]       a_sh;        // 被除数移位寄存器（逐位左移供出 MSB）
    reg [WB:0]         rem;         // 余数（多一位防溢出）
    reg [WQ-1:0]       q_u;         // 无符号商
    reg [7:0]          cnt;
    reg                busy;

    //   ⚠️⚠️ 商的符号必须【在启动那一拍锁存】！
    //      踩过的坑（2026-09-27，N 路并行后才暴露）：
    //      原写法在 cnt==ITER-1（启动后第 WA 拍）才用【当拍】的 q_neg 补符号，
    //      而 q_neg 是 a/b 的【组合】函数 —— 那时 a 早就不是本次的被除数了：
    //        · N=1：上游在 done 之前不会换操作数总线，侥幸正确
    //        · N=8：操作数总线每几拍换一次 → 补到【别的像素】的符号上
    //      现象：|q| 正确但符号随机翻转（x 差 2 倍幅值，y 大部分时候侥幸对）
    //            → 逐点误差只有个别点爆掉，极难从波形上看出来。
    //      正确做法：启动时把它锁进 q_neg_r，末尾只认锁存值。
    reg                q_neg_r;

    // 一次迭代的组合逻辑
    wire               bit_in = a_sh[WA-1];
    wire [WB:0]        trial  = {rem[WB-1:0], bit_in};
    wire [WB:0]        b_ext  = b_lat;          // ⚠️ 用锁存值，不能用 {1'b0, b_abs}
    wire               ge     = (trial >= b_ext);
    wire [WB:0]        rem_n  = ge ? (trial - b_ext) : trial;
    wire [WQ-1:0]      q_n    = {q_u[WQ-2:0], ge};

    always @(posedge clk) begin
        if (!rst_n) begin
            busy     <= 1'b0;
            done     <= 1'b0;
            div_zero <= 1'b0;
            q        <= {WQ{1'b0}};
            a_sh     <= {WA{1'b0}};
            rem      <= {(WB+1){1'b0}};
            q_u      <= {WQ{1'b0}};
            cnt      <= 8'd0;
            q_neg_r  <= 1'b0;
            b_lat    <= {(WB+1){1'b0}};
        end else begin
            done <= 1'b0;

            if (start && !busy) begin
                if (b_zero) begin
                    // 除数为 0：立即返回，避免不定态
                    q        <= {WQ{1'b0}};
                    div_zero <= 1'b1;
                    done     <= 1'b1;
                end else begin
                    a_sh     <= a_abs;
                    rem      <= {(WB+1){1'b0}};
                    q_u      <= {WQ{1'b0}};
                    cnt      <= 8'd0;
                    busy     <= 1'b1;
                    div_zero <= 1'b0;
                    q_neg_r  <= q_neg;          // ⭐ 启动时锁存符号（不是末尾现取）
                    b_lat    <= {1'b0, b_abs};  // ⭐ 启动时锁存除数（迭代中不再看输入）
                end
            end else if (busy) begin
                rem  <= rem_n;
                q_u  <= q_n;
                a_sh <= {a_sh[WA-2:0], 1'b0};
                cnt  <= cnt + 8'd1;

                if (cnt == ITER[7:0] - 8'd1) begin
                    busy <= 1'b0;
                    // 补符号：向零截断。⚠️ 用锁存的 q_neg_r，不能用组合的 q_neg
                    q    <= q_neg_r ? (~q_n + 1'b1) : q_n;
                    done <= 1'b1;
                end
            end
        end
    end

endmodule
