//=============================================================================
// bilinear.v
//   双线性插值（4 邻域）—— 两级流水，支持 1 通道（灰度）或 3 通道（彩色）
//
//   p00=(x0,y0)  p10=(x0+1,y0)
//   p01=(x0,y0+1) p11=(x0+1,y0+1)
//
//   out = (1-fx)(1-fy)·p00 + fx(1-fy)·p10 + (1-fx)fy·p01 + fx·fy·p11
//
//   实现上先横后纵分解，减少乘法器：
//       a = (1-fx)·p00 + fx·p10        ← 上行横向插值，放大 2^16 倍
//       b = (1-fx)·p01 + fx·p11        ← 下行横向插值
//       out = ((1-fy)·a + fy·b) >> 32  ← 纵向插值，结果放大 2^32 倍
//
//   fx / fy 是 Q16.16 的小数部分（0 ~ 65535），所以
//       fx 的"数值"= fx/65536，"1-fx" = (65536-fx)/65536
//
//---------------------------------------------------------------------------
//   ⚠️ 为什么是两级流水（综合实测踩出来的）
//---------------------------------------------------------------------------
//   最初把"4 次乘法 → 加法 → 2 次乘法 → 42 位加法 → 舍入"全塞在一拍里，
//   综合报告 WNS = -6.878 ns（10 ns 周期下最差路径 16.9 ns），时序不收敛。
//
//   现在拆成两级：
//       第 1 级：横向插值 a / b（4 个 17×8 乘法 + 加法）
//       第 2 级：纵向插值 + 舍入（2 个 17×25 乘法 + 42 位加法）
//   代价是延迟从 1 拍变成 2 拍 —— 调用方（remap_core）要多等一拍。
//
//   ⚠️⚠️ 延迟 = 2 拍，常量。改动流水级数必须同步改 remap_core 的等待状态数。
//       **多通道不是靠加流水级数做的** —— 见下。
//
//---------------------------------------------------------------------------
//   ⭐ 多通道（NCH）：为什么是"复制数据通路"而不是"分时复用"（2026-09-29 彩色步 C2）
//---------------------------------------------------------------------------
//   三个通道的插值权重 fx/fy 是【同一套】（几何变换与颜色无关），只有像素值
//   不同。所以有两个选择：
//
//     (a) 分时复用：一套乘法器，3 个通道轮流跑 ⇒ 延迟 2 拍 → 6 拍
//     (b) 复制数据通路：三套乘法器并行 ⇒ 延迟仍是 2 拍
//
//   本项目的判据是**速度优先**：核当前 7.16 拍/像素，其中 C 级占 2 拍 —
//   走 (a) 会变成约 11 拍/像素，**慢 50%**，无论画质多好都不划算。
//   走 (b) 只是多占乘法器：DSP 从 15 块涨到约 30 块（芯片有 220 块，占 14%），
//   **关键路径深度不变**（每级的逻辑深度一模一样，只是复制了三份）。
//   ⇒ 选 (b)：**多花面积，不花时间。**
//
//   ⚠️ 数据排布：p00/p10/p01/p11/pixel 都是 `NCH*PIX_W` 位，
//      通道 [0] 在最低位。通道顺序由调用方定义（见 remap_core 的 R/G/B 约定）。
//
//---------------------------------------------------------------------------
//   ⭐ 饱和（2026-09-29 加）—— 防御性，不是在修 bug
//---------------------------------------------------------------------------
//   ⚠️ 先把话说明白：**对 8 bit 输入，这个饱和永远不会被触发。** 推导：
//        a = ifx·p00 + fx·p10 ≤ (ifx+fx)·255 = 65536·255
//        acc = ify·a + fy·b ≤ 65536·65536·255 = 255·2^32
//        rnd = acc + 2^31 ≤ 255.5·2^32  ⇒  rnd[41:32] ≤ 255
//      （四舍五入加的是【半个 LSB】，不是整整一个，所以够不到 256）
//   ⇒ 这是**保险**，不是修复。留着它的理由：
//      · 代价约 3 个 LUT/通道（一个比较器 + 一个 mux），可以忽略；
//      · 一旦将来 PIX_W、数据来源或钳位策略变化，它保证结果不会
//        "白翻黑"（一个通道翻 0 就是一个色斑，肉眼极刺眼）。
//   ⇒ **不要因为"没触发"就删掉它**，它是给未来的改动兜底的。
//
//   ⚠️ 边界钳位【不】在本模块内做 —— 由调用方先把 (x0,y0) 钳到合法范围，
//      本模块只负责插值。这样划分是因为只有调用方知道图像尺寸。
//=============================================================================
`timescale 1ns / 1ps

module bilinear #(
    parameter integer PIX_W = 8,        // 每通道像素位宽（灰度 8）
    parameter integer NCH   = 1         // 通道数：1 = 灰度，3 = 彩色
)(
    input  wire                 clk,
    input  wire                 rst_n,

    // 四个邻域像素（NCH 个通道打包，通道 [0] 在最低位）
    input  wire [NCH*PIX_W-1:0] p00,
    input  wire [NCH*PIX_W-1:0] p10,
    input  wire [NCH*PIX_W-1:0] p01,
    input  wire [NCH*PIX_W-1:0] p11,

    // 小数权重，Q16.16 的纯小数部分（0 ~ 65535）—— 三个通道共用
    input  wire [15:0]          fx,
    input  wire [15:0]          fy,

    input  wire                 valid_in,

    output reg  [NCH*PIX_W-1:0] pixel,
    output reg                  valid_out        // 比 valid_in 晚 2 拍
);

    // 1-fx / 1-fy（Q16.16 意义下的补数）—— 三个通道共用
    wire [16:0] ifx = 17'd65536 - {1'b0, fx};

    //========================================================================
    // 共享的第 1 级控制寄存器（fy 打拍、valid 打拍）
    //========================================================================
    reg [15:0] fy_r;
    reg        v1;

    always @(posedge clk) begin
        if (!rst_n) begin
            fy_r <= 16'd0;
            v1   <= 1'b0;
        end else begin
            fy_r <= fy;
            v1   <= valid_in;
        end
    end

    //========================================================================
    // 每个通道一套数据通路（并行，不增加流水级数）
    //========================================================================
    genvar gi;
    generate
    for (gi = 0; gi < NCH; gi = gi + 1) begin : g_ch

        wire [PIX_W-1:0] c00 = p00[gi*PIX_W +: PIX_W];
        wire [PIX_W-1:0] c10 = p10[gi*PIX_W +: PIX_W];
        wire [PIX_W-1:0] c01 = p01[gi*PIX_W +: PIX_W];
        wire [PIX_W-1:0] c11 = p11[gi*PIX_W +: PIX_W];

        //--------------------------------------------------------------------
        // 第 1 级：横向插值（结果放大 2^16 倍）
        //--------------------------------------------------------------------
        reg  [24:0] a_r;        // 上行插值
        reg  [24:0] b_r;        // 下行插值

        wire [24:0] a_c = ifx * c00 + fx * c10;     // 17bit × 8bit → 25bit
        wire [24:0] b_c = ifx * c01 + fx * c11;

        always @(posedge clk) begin
            if (!rst_n) begin
                a_r <= 25'd0;
                b_r <= 25'd0;
            end else begin
                a_r <= a_c;
                b_r <= b_c;
            end
        end

        //--------------------------------------------------------------------
        // 第 2 级：纵向插值（再放大 2^16 倍，共放大 2^32 倍）+ 四舍五入 + 饱和
        //--------------------------------------------------------------------
        wire [16:0]      ify_r = 17'd65536 - {1'b0, fy_r};
        wire [41:0]      acc   = ify_r * a_r + fy_r * b_r;   // 17bit × 25bit → 42bit
        wire [41:0]      rnd   = acc + 42'h8000_0000;        // 2^31 = 半个 LSB
        wire [PIX_W-1:0] sat   = (rnd[41:32] > {PIX_W{1'b1}})     // ⭐ 饱和，不截断
                               ? {PIX_W{1'b1}}
                               : rnd[PIX_W+31:32];

        always @(posedge clk) begin
            if (!rst_n) begin
                pixel[gi*PIX_W +: PIX_W] <= {PIX_W{1'b0}};
            end else if (v1) begin
                pixel[gi*PIX_W +: PIX_W] <= sat;
            end
        end

    end
    endgenerate

    always @(posedge clk) begin
        if (!rst_n) valid_out <= 1'b0;
        else        valid_out <= v1;
    end

endmodule
