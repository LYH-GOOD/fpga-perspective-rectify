//=============================================================================
// homography_calc.v
//   单应变换坐标计算核（行为级 / 定点精度验证版）
//
//   功能：给定【输出】像素坐标 (u,v) 与单应逆矩阵 H^-1 的 8 个参数，
//         算出该输出像素在【输入图像】中对应的位置 (x,y)。
//
//   数学（反向映射 —— CLAUDE.md 铁律 3）：
//         x = (h11*u + h12*v + h13) / (h31*u + h32*v + 1)
//         y = (h21*u + h22*v + h23) / (h31*u + h32*v + 1)
//         h33 归一化为 1.0，不单独传参
//
//---------------------------------------------------------------------------
//   ⭐ 定点方案：坐标归一化（方案 B）—— 这是实测选出来的，不是拍脑袋
//---------------------------------------------------------------------------
//   直接按像素坐标存 Q16.16 会翻车：
//     h31 / h32 只有 ~1e-4 量级，而 Q16.16 的分辨率是 1.5e-5，
//     只剩约 3 位有效数字；再乘 u（最大 1280）进分母，最后被 x 放大一次。
//     实测坐标误差 11.57 px —— 远超 1.0 px 指标。
//
//   修正办法：把坐标归一化到 [0,1]（尺度 NORM_SCALE，取 2 的幂），
//   并让 PS 侧把参数【预乘 NORM_SCALE】后再发过来：
//         u = su · NORM_SCALE,  v = sv · NORM_SCALE
//         x = (a11·su + a12·sv + a13) / (a31·su + a32·sv + 1)
//         其中 a11 = h11·NORM_SCALE, a12 = h12·NORM_SCALE, a13 = h13
//              a31 = h31·NORM_SCALE, a32 = h32·NORM_SCALE
//   此时 a31 约为 0.1~1 量级，Q16.16 下有效数字充足。
//   实测坐标误差 0.033 px —— 提升 351 倍。
//
//   为什么 NORM_SCALE 必须取 2 的幂：su = u·2^FRAC/NORM_SCALE 变成纯移位，
//   无舍入、无累积误差。取 2048 可覆盖到 2048 宽/高的图像。
//
//---------------------------------------------------------------------------
//   本模块是【组合逻辑 + 行为级除法】的"先跑通"版本：
//     - 目的是快速验证定点方案与公式是否正确
//     - '/' 综合出的除法器面积大、时序差
//     - 它**永远不参与综合**，只作为 coord_gen（递推版）的对照参考 / 黄金模型
//   ⚠️ 不要拿本模块综合后的资源数字去写报告。
//   ⚠️ 提速不走本模块：实际路线是在 coord_gen 里放 8 路并行 div_seq
//      （见 coord_gen.v 文件头「设计二」与 CLAUDE.md「为什么选并行」）。
//=============================================================================
`timescale 1ns / 1ps

module homography_calc #(
    parameter integer FRAC_BITS  = 16,      // Q16.16 的小数位数
    parameter integer NORM_SCALE = 2048     // 坐标归一化尺度，必须是 2 的幂
)(
    // ---- 单应逆矩阵 H^-1 的 8 个参数（Q16.16，已预乘 NORM_SCALE）----
    input  wire signed [31:0] a11,
    input  wire signed [31:0] a12,
    input  wire signed [31:0] a13,
    input  wire signed [31:0] a21,
    input  wire signed [31:0] a22,
    input  wire signed [31:0] a23,
    input  wire signed [31:0] a31,
    input  wire signed [31:0] a32,

    // ---- 输出像素坐标（整数）----
    input  wire        [11:0] u,            // 输出图像列
    input  wire        [11:0] v,            // 输出图像行

    // ---- 结果 ----
    output wire signed [31:0] x_q,          // 输入图像列，Q16.16
    output wire signed [31:0] y_q,          // 输入图像行，Q16.16
    output wire signed [31:0] d_q,          // 分母 d，Q16.16（调试用）
    output wire               div_by_zero,  // d == 0，坐标无意义
    output wire               out_overflow  // 结果超出 32 位可表示范围
);

    //------------------------------------------------------------------------
    // 归一化坐标 su = u / NORM_SCALE，用纯移位实现（NORM_SCALE 是 2 的幂）
    //   su 以 Q16.16 表示： su_q = u · 2^FRAC / NORM_SCALE = u << (FRAC_BITS - log2(NORM_SCALE))
    //------------------------------------------------------------------------
    localparam integer NORM_SHIFT = FRAC_BITS - $clog2(NORM_SCALE);   // 16 - 11 = 5

    wire [16:0] su = {5'd0, u} <<< NORM_SHIFT;     // 最大 4095<<5 = 131040 → 17 位
    wire [16:0] sv = {5'd0, v} <<< NORM_SHIFT;

    //------------------------------------------------------------------------
    // 加宽到 48 位再做乘加
    //   32 位参数 × 17 位归一化坐标 → 最多 49 位。这里用 48 位、并依赖
    //   参数的合理取值范围（|a| < 2^27 量级）保证不溢出。
    //   ⚠️ Verilog 乘法结果宽度 = 操作数最大宽度，必须显式加宽，
    //      否则会静默截断 —— 新手极容易踩的坑。
    //------------------------------------------------------------------------
    wire signed [47:0] a11_e = {{16{a11[31]}}, a11};
    wire signed [47:0] a12_e = {{16{a12[31]}}, a12};
    wire signed [47:0] a13_e = {{16{a13[31]}}, a13};
    wire signed [47:0] a21_e = {{16{a21[31]}}, a21};
    wire signed [47:0] a22_e = {{16{a22[31]}}, a22};
    wire signed [47:0] a23_e = {{16{a23[31]}}, a23};
    wire signed [47:0] a31_e = {{16{a31[31]}}, a31};
    wire signed [47:0] a32_e = {{16{a32[31]}}, a32};
    wire signed [47:0] one_e = 48'sd1 <<< FRAC_BITS;   // Q16.16 的 1.0

    wire signed [47:0] su_e  = {31'd0, su};            // 零扩展：su 非负
    wire signed [47:0] sv_e  = {31'd0, sv};

    // 乘完右移 FRAC_BITS 还原回 Q16.16
    wire signed [47:0] xn = ((a11_e * su_e) >>> FRAC_BITS)
                          + ((a12_e * sv_e) >>> FRAC_BITS)
                          + a13_e;
    wire signed [47:0] yn = ((a21_e * su_e) >>> FRAC_BITS)
                          + ((a22_e * sv_e) >>> FRAC_BITS)
                          + a23_e;
    wire signed [47:0] d  = ((a31_e * su_e) >>> FRAC_BITS)
                          + ((a32_e * sv_e) >>> FRAC_BITS)
                          + one_e;

    //------------------------------------------------------------------------
    // 除法：x = xn / d
    //   xn 是 Q16.16（实际值 = xn / 2^16），d 同理，两者相除 2^16 约掉，
    //   但结果要还原成 Q16.16 → x_q = (xn << 16) / d
    //------------------------------------------------------------------------
    wire signed [63:0] xn_sh = {{16{xn[47]}}, xn} <<< FRAC_BITS;
    wire signed [63:0] yn_sh = {{16{yn[47]}}, yn} <<< FRAC_BITS;
    wire signed [63:0] d_64  = {{16{d[47]}}, d};

    wire               zero = (d == 48'sd0);
    wire signed [63:0] xq64 = zero ? 64'sd0 : (xn_sh / d_64);
    wire signed [63:0] yq64 = zero ? 64'sd0 : (yn_sh / d_64);

    //------------------------------------------------------------------------
    // 结果限幅 + 溢出标志
    //------------------------------------------------------------------------
    wire x_ovf = (xq64 > 64'sd2147483647) || (xq64 < -64'sd2147483648);
    wire y_ovf = (yq64 > 64'sd2147483647) || (yq64 < -64'sd2147483648);

    assign x_q = x_ovf ? (xq64[63] ? 32'sh80000000 : 32'sh7FFFFFFF) : xq64[31:0];
    assign y_q = y_ovf ? (xq64[63] ? 32'sh80000000 : 32'sh7FFFFFFF) : yq64[31:0];

    assign d_q          = d[31:0];
    assign div_by_zero  = zero;
    assign out_overflow = x_ovf | y_ovf;

endmodule
