//=============================================================================
// line_buf.v
//   流式重映射的行缓存（Line Buffer）
//
//   作用：把【按行流入】的输入像素存起来，让重映射引擎能【任意寻址】地取用。
//         这是"主干像素流不落 DDR"（铁律 1）在硬件上的落点 ——
//         数据只在片上 BRAM 里转一圈，从不进 DDR。
//
//---------------------------------------------------------------------------
//   ⭐ 深度 ROWS 怎么定 —— 已实测，不是拍脑袋
//---------------------------------------------------------------------------
//   输出第 v 行所需的输入像素落在一条直线上，这条线的垂直跨度就是所需行数。
//   实测规律（sim/golden/analyze_band.py）：
//
//       所需行数 ≈ W_out × tan(θ)，  θ = 文档在【图像里】的旋转角
//
//   ⚠️ 决定深度的是【旋转】，不是倾角：
//        60° 倾角 + 无旋转 → 只要 2 行
//        60° 倾角 + 旋转 3°  → 61 行
//        60° 倾角 + 旋转 10° → 196 行
//   所以本模块的 ROWS 做成参数，按实际演示条件选（默认 64，覆盖约 2.9°）。
//
//---------------------------------------------------------------------------
//   存储组织
//---------------------------------------------------------------------------
//   地址 = (row mod ROWS) × W_ACTIVE + col
//   即"行号对 ROWS 取模"做环形回绕：写满第 ROWS 行后回头覆盖最老的一行。
//   安全性前提：读侧永远不读比 ROWS 行更老的数据 —— 这由上层流控保证
//   （见 remap_core.v 的 in_stall）。
//
//---------------------------------------------------------------------------
//   ⭐ ROWS 为什么不再是 2 的幂（2026-09-29 彩色步 C1）
//---------------------------------------------------------------------------
//   灰度时 ROWS=256，`row mod ROWS` 正好是 `row[7:0]` 一个位切片 —— 零成本。
//   彩色时每像素 16 bit（RGB565），行缓存开销变成 2 倍，256 行 × 1024 列 ×
//   16 bit 要 **128 块 BRAM，芯片只有 140 块**，装不下。
//   降到 192 行 → 96 块（74%），且 192 > 实测最大跨度 166 行 ✓。
//
//   ⚠️ 192【不是】2 的幂，位切片不再等于取模 —— 这里必须显式算 `row mod 192`。
//      这个函数落在【读地址通路】上（rd_row → slot → slot×W_ACTIVE → BRAM），
//      所以不能随手写 `row % ROWS` 让综合器去生成通用取模：那会在地址路上
//      串两个乘法器。本项目 2026-09-27 就因为地址路上多了一个 12 位比较器，
//      WNS 掉到 -0.222 ns、直接出不了比特流。地址路只允许
//      「寄存器 → 小常量乘法 → BRAM」。
//
//   192 = 3 × 64 的快速取模：
//        row = 64·q + r      (q = row[ROW_AW-1:6]，r = row[5:0])
//        row mod 192 = ((q mod 3)·64) + r
//   q ≤ 125 时，  q mod 3 = q - 3·((q·43) >> 7)      ← 只用一个小常量乘法
//        （43/128 = 0.33594，在 q < 126 范围内 floor 恒等于 floor(q/3)；
//          ROW_AW = 12 ⇒ q ≤ 63，留一倍余量）
//   ⚠️ 这个恒等式【不靠推理】—— line_buf_ring192_tb.v 里对全部 4096 个行号
//      逐值对比 RTL 与 `%` 的结果。
//---------------------------------------------------------------------------
//
//   注意：本模块【不做边界钳位】。越界的行列地址读出来是垃圾数据，
//         钳位由调用方（行引擎）负责 —— 因为只有它知道图像尺寸。
//
//   写侧：1 像素/时钟
//   读侧：1 像素/时钟，读地址到数据有 1 拍延迟（BRAM 特性）
//
//=============================================================================
//   ⭐ 2026-10-22 · 2 体（按列 bit0）：把 B 级从 5 拍压到 3 拍
//=============================================================================
//   按 **列号 bit0** 把存储切成 2 个体：
//
//       mem_e 存偶数列，mem_o 存奇数列
//       体内地址 = slot * (W_ACTIVE/2) + (col>>1)
//       总容量 = 2 × ROWS × (W_ACTIVE/2) = ROWS × W_ACTIVE   ← 一块 BRAM 都不多
//
//   ⭐ 为什么够用：四邻域 (x0,y0) (x0+1,y0) (x0,y1) (x0+1,y1) 里，
//      **x0 与 x0+1 的 bit0 必然相反** ⇒ 每拍两个体各读 1 个 ⇒ 一行两列 1 拍读完，
//      两行 = 2 拍。
//
//   ⚠️ 前提：W_ACTIVE 必须是偶数（1024/1280/16 ✓）。
//   ⚠️ 端口语义：`rd_col_e` 必须是**偶数列**、`rd_col_o` 必须是**奇数列**；
//      调用方在锁存那一拍就把"谁是偶、谁是奇"选好（见 remap_core 的 b_col_even/b_col_odd），
//      所以这里不需要任何比较器或 mux 进地址路。
//   ⚠️ 4 体版本（按行b0+列b0 切）实测把 BRAM 从 96 顶到 128（91%），不可上板；
//      本 2 体版本就是退一步的方案。
//=============================================================================
`timescale 1ns / 1ps

module line_buf #(
    parameter integer PIX_W    = 8,        // 像素位宽（v1 灰度 8bit）
    parameter integer W_ACTIVE = 1280,     // 实际行宽（米用多少列）
    parameter integer ROWS     = 64,       // 缓存行数 = 最大垂直跨度
    parameter integer ROW_AW   = 12        // 行号的位宽（输入图像高度 ≤4095）
)(
    input  wire                 clk,
    input  wire                 rst_n,       // 同步低电平复位

    // ---------------- 写侧：输入像素流 ----------------
    input  wire                 wr_en,
    input  wire [ROW_AW-1:0]    wr_row,      // 输入图像内的行号，帧内从 0 递增
    input  wire [15:0]          wr_col,      // 列号
    input  wire [PIX_W-1:0]     wr_data,
    input  wire                 wr_last,     // ⭐ 本拍写入的是本行【最后一个】像素
    input  wire                 frame_start, // ⭐ 帧首脉冲（= 新一帧第一个像素被写入）
                                             //   用来把 rows_written 归零 ⇒ 行数变成"每帧"的

    // ---------------- 读侧：2 个体口（偶数列 / 奇数列，每拍各读 1 个）--------
    //   ⚠️ rd_col_e 必须是偶数列、rd_col_o 必须是奇数列（调用方保证）
    input  wire                 rd_en,
    input  wire [ROW_AW-1:0]    rd_row_e, rd_row_o,
    input  wire [15:0]          rd_col_e, rd_col_o,
    output reg  [PIX_W-1:0]     rd_data_e, rd_data_o,
    output reg                  rd_valid,    // rd_data_* 有效的标志（比 rd_en 晚 1 拍）

    // ---------------- 状态 ----------------
    output reg  [ROW_AW-1:0]    rows_written // 已写入的行数（= 最高行号 + 1）
);

    //------------------------------------------------------------------------
    // 存储体
    //------------------------------------------------------------------------
    //   2 体（按列 bit0）：每体存一半列 ⇒ 两个独立数组，各自 1 写 + 1 读。
    localparam integer HALF_W   = W_ACTIVE / 2;
    localparam integer DEPTH2   = ROWS * HALF_W;
    localparam integer ADDR2_AW = $clog2(DEPTH2);
    localparam integer HALF_AW  = $clog2(HALF_W);
    localparam integer SLOT_AW  = $clog2(ROWS);

    reg [PIX_W-1:0] mem_e [0:DEPTH2-1];   // 偶数列
    reg [PIX_W-1:0] mem_o [0:DEPTH2-1];   // 奇数列

    //------------------------------------------------------------------------
    // 行号 → 环形槽位（row mod ROWS）
    //------------------------------------------------------------------------
    localparam integer ROWS_POW2 = ((ROWS & (ROWS - 1)) == 0);
    //   ⭐ 2026-10-25：原来只认死 192 = 3×64。现在推广到 **ROWS = 64×m**（m ≥ 2）。
    //   恒等式（对任意 m 成立，不靠推理）：
    //       row = 64*q + r   ⇒   row mod (64m) = 64*(q mod m) + r
    //   要求 ROW_AW ≤ 13 ⇒ row < 8192 ⇒ q < 128，6 位就够，q mod m 的电路很小。
    //   ⚠️ 别退回 `row % ROWS`：那是对 **ROW_AW 位全宽**取模，会串乘法器；
    //      这里对 **q（6 位）**取模，综合出来只是几个减法。
    localparam integer ROWS_M     = ROWS / 64;
    localparam integer ROWS_Mx64  = ((ROWS % 64) == 0) && (ROWS_M >= 2) && (ROW_AW <= 13);
    localparam [ROW_AW-1:0] ROWS_M_W = ROWS_M;      // 窄化成 ROW_AW 位，避免 32 位取模

    function [SLOT_AW-1:0] row_to_slot;
        input [ROW_AW-1:0] row;
        //   ⚠️ q / qm 必须声明成 **ROW_AW 宽**：Verilog 里 `a << 6` 的结果宽度
        //      跟随 a 本身，用窄变量会在 `qm<<6` 处截断（192 那版就是这么写的）。
        reg   [ROW_AW-1:0] q;       // row / 64
        reg   [ROW_AW-1:0] qm;      // q mod ROWS_M
        begin
            if (ROWS_POW2) begin
                // 2 的幂：位切片，零成本（灰度版走这条）
                row_to_slot = row[SLOT_AW-1:0];
            end else if (ROWS_Mx64) begin
                q           = row >> 6;
                qm          = q % ROWS_M_W;
                row_to_slot = (qm << 6) | row[5:0];
            end else begin
                // 兜底：交给综合器算常量取模。⚠️ 会串两个乘法器，
                // 只用于"能跑但慢"的非关键配置，主力配置必须走上面两条。
                row_to_slot = row % ROWS;
            end
        end
    endfunction

    wire [SLOT_AW-1:0] wr_slot = row_to_slot(wr_row);

    // 地址 = 槽位 × 半宽 + (列/2)。HALF_W 是常数，综合成移位+加法，不占 DSP。
    //   ⚠️ 列号 bit0 已经拿去选体了，所以这里右移一位。
    wire [HALF_AW-1:0]  wr_c    = wr_col[HALF_AW:1];
    wire [ADDR2_AW-1:0] wr_addr = wr_slot * HALF_W + wr_c;

    wire [SLOT_AW-1:0]  rd_slot_e = row_to_slot(rd_row_e);
    wire [SLOT_AW-1:0]  rd_slot_o = row_to_slot(rd_row_o);
    wire [ADDR2_AW-1:0] rd_addr_e = rd_slot_e * HALF_W + rd_col_e[HALF_AW:1];
    wire [ADDR2_AW-1:0] rd_addr_o = rd_slot_o * HALF_W + rd_col_o[HALF_AW:1];

    //------------------------------------------------------------------------
    // 写口（按列 bit0 落到偶/奇体）
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (wr_en) begin
            if (wr_col[0]) mem_o[wr_addr] <= wr_data;
            else           mem_e[wr_addr] <= wr_data;
        end
    end

    //------------------------------------------------------------------------
    // 读口（两个体各一个；BRAM 同步读：地址给出一拍后数据有效）
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (!rst_n) begin
            rd_valid  <= 1'b0;
            rd_data_e <= {PIX_W{1'b0}};
            rd_data_o <= {PIX_W{1'b0}};
        end else begin
            rd_valid <= rd_en;
            if (rd_en) begin
                rd_data_e <= mem_e[rd_addr_e];
                rd_data_o <= mem_o[rd_addr_o];
            end
        end
    end

    //------------------------------------------------------------------------
    // 已写入行计数（供上层做流控）
    //   ⭐ 语义 = 【整行写完】的行数。判据是 wr_last（本拍是本行最后一列）。
    //------------------------------------------------------------------------
    //   ⚠️⚠️ 踩过的坑（上板"最大差异 57 灰阶"的根因，只错第 0 行）
    //
    //   原来的写法是：
    //       if (wr_en && wr_row >= rows_written) rows_written <= wr_row + 1'b1;
    //   这个条件在【本行第一个像素】就成立 —— 于是第 R 行刚写了 1 个像素，
    //   rows_written 就变成 R+1。语义悄悄从"第 R 行写完了"变成
    //   "第 R 行开始写了"。
    //
    //   上层用 rows_written > y1 判断"要读的行到齐没有"，于是提前放行，
    //   读到一行【只写了一半】的数据 —— 仿真里读出 X，板上读出 BRAM 端口
    //   残留值（实测最大 57 灰阶 = 165 的阶跃 × fy≈0.35）。
    //
    //   ⭐ 为什么只在第 0 行暴露：
    //     核一开工（S_IDLE 只等 1 行）就正好顶在写前沿上，第 0 行要读的 y1
    //     恰好是"正在写"的那一行；之后输入被流控顶在前面 ROWS 行，
    //     读侧永远落后写前沿几十~几百行，race 再也碰不上。
    //     → 这是典型的"只在边界暴露"的 bug，小尺寸 TB 难触发。
    //------------------------------------------------------------------------
    always @(posedge clk) begin
        if (!rst_n) begin
            rows_written <= {ROW_AW{1'b0}};
        end else if (frame_start) begin
            //   ⭐ 帧首归零（2026-09-29 帧门的一部分）。
            //   ⚠️ 此刻上一帧的输入【已经全部收完】（帧首 = tlast 之后的那一拍），
            //      所以清掉不会丢行 —— 清了它，rows_written 的语义才从
            //      "上电至今写了多少行"变成"本帧写了多少行"，多帧才成立。
            //   ⚠️ 优先级高于 wr_en && wr_last：帧首那拍不可能是本行最后一列
            //      （除非 w_in==1，那种退化情形下"先归零再计一行"也正是想要的）。
            rows_written <= {ROW_AW{1'b0}};
        end else if (wr_en && wr_last) begin
            rows_written <= wr_row + 1'b1;
        end
    end

endmodule
